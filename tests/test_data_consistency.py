"""Phase 12 Data Consistency and Integrity Verification Suite.

Validates all 10 core business and spatial integrity rules across both
isolated test fixtures and real processed Parquet datasets:
1. Every current owner has a valid claim.
2. Suspicious rejected runs cannot claim zones.
3. Total owned zones matches leaderboard totals.
4. No duplicated claim IDs exist.
5. Same-owner visits do not count as takeovers.
6. Timestamps are processed chronologically.
7. H3 cells are valid Uber H3 index representations.
8. Raw datasets are unchanged and structurally valid.
9. Parquet schemas are consistent across all tables.
10. Replay incremental results match batch results (0 mismatches).
"""

from __future__ import annotations

from pathlib import Path
import h3
import pandas as pd
import pytest

from src.realtime.batch_processor import BatchProcessor
from src.realtime.incremental_ownership import IncrementalOwnershipEngine
from src.utils import get_project_root


@pytest.fixture(scope="module")
def root_dir() -> Path:
    return get_project_root()


@pytest.fixture(scope="module")
def real_datasets(root_dir: Path):
    parquet_dir = root_dir / "data" / "parquet"
    return {
        "curr": pd.read_parquet(parquet_dir / "current_ownership"),
        "hist": pd.read_parquet(parquet_dir / "ownership_history"),
        "claims": pd.read_parquet(parquet_dir / "claim_events"),
        "risk": pd.read_parquet(parquet_dir / "run_anomalies"),
        "lb": pd.read_parquet(parquet_dir / "leaderboard"),
        "points": pd.read_parquet(parquet_dir / "eligible_points"),
    }


def test_rule_1_every_current_owner_has_valid_claim(real_datasets) -> None:
    """Rule 1: Every current owner originates from a confirmed qualifying claim event."""
    curr = real_datasets["curr"]
    claims = real_datasets["claims"]

    valid_claim_ids = set(claims["claim_id"].dropna())
    assert not curr.empty, "Current ownership table is empty"

    unmatched = [cid for cid in curr["latest_claim_id"] if cid not in valid_claim_ids]
    assert len(unmatched) == 0, f"Found {len(unmatched)} current owners without an eligible claim: {unmatched[:5]}"


def test_rule_2_suspicious_rejected_runs_cannot_claim_zones(real_datasets) -> None:
    """Rule 2: Suspicious or high-risk runs must be quarantined and forbidden from claiming territory."""
    curr = real_datasets["curr"]
    hist = real_datasets["hist"]
    risk = real_datasets["risk"]

    rejected_runs = set(risk[risk["risk_category"] != "NORMAL"]["run_id"])
    assert len(rejected_runs) > 0, "Expected non-zero quarantined runs"

    # Current ownership check
    invalid_current = [r for r in curr["acquired_in_run"] if r in rejected_runs]
    assert len(invalid_current) == 0, f"Found {len(invalid_current)} current zones acquired in rejected runs"

    # Historical ownership check
    invalid_history = [r for r in hist["run_id"] if r in rejected_runs]
    assert len(invalid_history) == 0, f"Found {len(invalid_history)} history events originating from rejected runs"


def test_rule_3_total_owned_zones_matches_leaderboard_totals(real_datasets) -> None:
    """Rule 3: Conservation of territory — Sum of zones owned on leaderboard equals total owned zones in current_ownership."""
    curr = real_datasets["curr"]
    lb = real_datasets["lb"]

    total_owned_curr = int(curr["current_owner_id"].dropna().count())
    total_owned_lb = int(lb["zones_owned"].sum())

    assert total_owned_curr == 308, f"Expected 308 active zones, found {total_owned_curr}"
    assert total_owned_lb == total_owned_curr, (
        f"Conservation violated: Leaderboard sum ({total_owned_lb}) != Current ownership total ({total_owned_curr})"
    )


def test_rule_4_no_duplicated_claim_ids_exist(real_datasets) -> None:
    """Rule 4: Every claim ID generated by the engine must be uniquely identifiable."""
    claims = real_datasets["claims"]
    hist = real_datasets["hist"]

    dup_claims = int(claims["claim_id"].duplicated().sum())
    assert dup_claims == 0, f"Found {dup_claims} duplicated claim_ids in claim_events"

    dup_hist = int(hist["claim_id"].duplicated().sum())
    assert dup_hist == 0, f"Found {dup_hist} duplicated claim_ids in ownership_history"


def test_rule_5_same_owner_visits_do_not_count_as_takeovers(real_datasets) -> None:
    """Rule 5: Revisiting an already owned zone is a SAME_OWNER_REVISIT, not a hostile takeover."""
    hist = real_datasets["hist"]

    revisit_takeovers = hist[(hist["event_type"] == "SAME_OWNER_REVISIT") & (hist["is_takeover"] == True)]
    assert len(revisit_takeovers) == 0, (
        f"Found {len(revisit_takeovers)} same-owner revisits incorrectly flagged as takeovers"
    )

    takeovers = hist[hist["event_type"] == "TAKEOVER"]
    assert all(takeovers["is_takeover"] == True), "All TAKEOVER events must have is_takeover == True"
    assert all(takeovers["runner_id"] != takeovers["prev_runner_id"]), (
        "Takeovers must have different runner_id from prev_runner_id"
    )


def test_rule_6_timestamps_processed_chronologically(real_datasets) -> None:
    """Rule 6: Within every H3 zone, claims must be strictly monotonic non-decreasing in time."""
    hist = real_datasets["hist"]

    non_monotonic_cells = []
    for cell, group in hist.groupby("h3_cell"):
        if not group["claim_timestamp_epoch"].is_monotonic_increasing:
            non_monotonic_cells.append(cell)

    assert len(non_monotonic_cells) == 0, (
        f"Found {len(non_monotonic_cells)} cells with non-chronological events: {non_monotonic_cells[:3]}"
    )


def test_rule_7_h3_cells_are_valid(real_datasets) -> None:
    """Rule 7: Every referenced H3 cell must be a valid Uber H3 Resolution 9 cell string."""
    curr = real_datasets["curr"]
    hist = real_datasets["hist"]

    all_cells = set(curr["h3_cell"]).union(set(hist["h3_cell"]))
    assert len(all_cells) > 0, "No H3 cells found"

    invalid_cells = [c for c in all_cells if not h3.is_valid_cell(str(c))]
    assert len(invalid_cells) == 0, f"Found {len(invalid_cells)} invalid H3 cells: {invalid_cells[:5]}"

    # Verify resolution is 9
    resolutions = {h3.get_resolution(str(c)) for c in all_cells}
    assert resolutions == {9}, f"Expected all cells to have H3 resolution 9, found {resolutions}"


def test_rule_8_raw_datasets_are_unchanged(root_dir: Path) -> None:
    """Rule 8: Ingestion and pipeline runs must never mutate or truncate original raw CSV files."""
    raw_csv = root_dir / "data" / "raw" / "gps_100k.csv"
    assert raw_csv.exists(), "Raw 100K CSV missing"

    # Count lines efficiently without loading entire file into memory
    with open(raw_csv, "r", encoding="utf-8") as f:
        line_count = sum(1 for _ in f)

    # 1 header + 100,000 data rows = 100,001 lines
    assert line_count == 100_001, f"Expected 100,001 lines in raw GPS CSV, found {line_count}"


def test_rule_9_parquet_schemas_are_consistent(root_dir: Path) -> None:
    """Rule 9: Exported Parquet tables must conform to defined schema contracts."""
    parquet_dir = root_dir / "data" / "parquet"

    expected_schemas = {
        "current_ownership": [
            "h3_cell", "current_owner_id", "previous_owner_id",
            "acquired_in_run", "acquired_at", "total_zone_claims", "total_zone_takeovers"
        ],
        "ownership_history": [
            "claim_id", "h3_cell", "runner_id", "run_id",
            "claim_timestamp", "claim_timestamp_epoch", "event_type", "is_takeover"
        ],
        "run_anomalies": [
            "run_id", "runner_id", "fraud_score", "risk_category"
        ],
        "leaderboard": [
            "runner_id", "zones_owned", "rank"
        ],
    }

    for table, req_cols in expected_schemas.items():
        table_path = parquet_dir / table
        assert table_path.exists(), f"Missing Parquet directory {table}"
        df = pd.read_parquet(table_path)
        missing = [c for c in req_cols if c not in df.columns]
        assert len(missing) == 0, f"Parquet table '{table}' missing required columns: {missing}"


def test_rule_10_replay_results_match_batch_results(real_datasets) -> None:
    """Rule 10: Incremental micro-batch replay yields 100% equivalence to Spark batch results."""
    points_df = real_datasets["points"]
    batch_curr = real_datasets["curr"]

    bp = BatchProcessor(batch_interval_s=5.0)
    engine = IncrementalOwnershipEngine()

    for batch in bp.partition_records_into_batches(points_df):
        engine.process_claims_batch(batch.claims, batch_id=batch.batch_id)

    batch_owners = dict(zip(batch_curr["h3_cell"], batch_curr["current_owner_id"]))
    replay_owners = {cell: rec.current_owner_id for cell, rec in engine.current_ownership.items()}

    assert len(replay_owners) == len(batch_owners), (
        f"Zone count mismatch: Replay ({len(replay_owners)}) != Batch ({len(batch_owners)})"
    )

    mismatches = [
        c for c, owner in replay_owners.items() if batch_owners.get(c) != owner
    ]
    assert len(mismatches) == 0, (
        f"Found {len(mismatches)} ownership mismatches between batch and replay: {mismatches[:5]}"
    )
