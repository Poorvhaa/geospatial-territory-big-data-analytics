"""Data Loading Service for Territory Intelligence BI Platform.

Reads preaggregated Parquet datasets generated by the Big Data pipeline using
PyArrow and Pandas. Does not initialize Spark or load raw multi-million point GPS tables,
ensuring rapid sub-second dashboard performance and low memory footprint.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import pandas as pd
import pyarrow.parquet as pq
import streamlit as st

from src.utils import get_project_root

logger = logging.getLogger(__name__)

